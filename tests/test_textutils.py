import pytest

from app import textutils as tu


@pytest.mark.parametrize(
    "raw, expected",
    [
        ("+7 (900) 000-00-11", "+79000000011"),
        ("8 900 000 00 12", "+79000000012"),
        ("8-900-000-00-14", "+79000000014"),
        ("89000000023", "+79000000023"),
        ("+7-900-000-00-31", "+79000000031"),
        ("8 (900) 000-00-18", "+79000000018"),
    ],
)
def test_phone_formats_are_normalized(raw, expected):
    assert tu.find_phones(f"Мой номер {raw}, звоните") == [expected]


def test_amounts_and_requisites_are_not_phones():
    text = "Оплатили 184 500 руб. по счёту №402, ИНН 7700000000, р/с 40702810000000000001, дважды по 38 900"
    assert tu.find_phones(text) == []


@pytest.mark.parametrize(
    "text, expected",
    [
        ("Бюджет до 55 000 руб. вместе с установкой", 55_000),
        ("Бюджет ориентировочно 1,2 млн руб.", 1_200_000),
        ("Цена вопроса до 70 тыс. Звоните +7 900 000 00 19", 70_000),
        ("Бюджет 200–250 тысяч.", 250_000),
        ("бюджет согласован — до 300 000 руб.", 300_000),
        ("Примерный бюджет на монтаж — 30 т.р.", 30_000),
        ("Нужен кондиционер до 40 тысяч", 40_000),
        ("с отсрочкой платежа до 30 дней", None),
        ("Оплатили счёт на 184 500 руб.", None),
    ],
)
def test_budget_parsing(text, expected):
    assert tu.parse_budget(text) == expected


@pytest.mark.parametrize(
    "text, expected",
    [
        ("Можете приехать на замер? Анна, +7 (900) 000-00-11", "Анна"),
        ("С уважением, Дмитрий Орлов, руководитель АХО", "Дмитрий Орлов"),
        ("Требую прислать мастера.\n\nЕлена Викторовна, 8-900-000-00-14", "Елена Викторовна"),
        ("Меня зовут Олег, хотел бы заказать монтаж. Квартира на 3 этаже.", "Олег"),
        ("Прошу выставить счёт-фактуру. ИП Громов А.С.", None),
        ("Спасибо. Заказ 4402.", None),
    ],
)
def test_person_name(text, expected):
    assert tu.find_person_name(text) == expected


def test_company_skips_own_name():
    text = "Пишет ООО «Прохлада-Сервис»? Нет, это ООО «Вектор-Плюс» открывает офис."
    assert tu.find_company(text, own_name="Прохлада-Сервис") == "ООО «Вектор-Плюс»"
    assert tu.find_company("Оплатил ИП Громов А.С. вчера") == "ИП Громов А.С."
    assert tu.find_company("Обычное письмо без организаций") is None


def test_summary_drops_greeting_and_keeps_first_sentence():
    body = "Здравствуйте! Нужен кондиционер в спальню 18 м², желательно инверторный и тихий. Бюджет до 55 000 руб."
    assert tu.summarize(body) == "Нужен кондиционер в спальню 18 м², желательно инверторный и тихий."
